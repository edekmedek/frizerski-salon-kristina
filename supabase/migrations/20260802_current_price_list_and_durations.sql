  source_code, category_id, name, price, duration_minutes, is_active, is_bookable, display_order
)
select imported.source_code,
       category.id,
       imported.name,
       imported.price,
       imported.duration_minutes,
       imported.is_active,
       coalesce(existing.is_bookable, true),
       imported.display_order
from imported_services imported
join public.service_categories category on category.code = imported.category_code
left join public.services existing on existing.source_code = imported.source_code
on conflict (source_code) do update
set category_id = excluded.category_id,
    name = excluded.name,
    price = excluded.price,
    duration_minutes = coalesce(excluded.duration_minutes, public.services.duration_minutes),
    is_active = excluded.is_active,
    display_order = excluded.display_order,
    updated_at = now();

